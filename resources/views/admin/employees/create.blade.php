<script>
function toggleLoginSection() {
    const isChecked = document.getElementById('login_enabled').checked;
    document.getElementById('loginDetailsContainer').style.display = isChecked ? '' : 'none';
    document.getElementById('loginDisabledNotice').style.display = isChecked ? 'none' : '';
    const passInput = document.getElementById('user_password');
    if (passInput) {
        if (!isChecked) {
            passInput.removeAttribute('required');
        } else if (document.getElementById('mode_create') && document.getElementById('mode_create').checked) {
            passInput.setAttribute('required', 'required');
        }
    }
}

function toggleUserMode() {
    const isCreate = document.getElementById('mode_create').checked;
    document.getElementById('newUserFields').style.display = isCreate ? '' : 'none';
    document.getElementById('linkUserFields').style.display = isCreate ? 'none' : '';
    const passInput = document.getElementById('user_password');
    if (passInput) {
        if (isCreate && document.getElementById('login_enabled').checked) {
            passInput.setAttribute('required', 'required');
        } else {
            passInput.removeAttribute('required');
        }
    }
}

function togglePassVisibility(inputId, btn) {
    const input = document.getElementById(inputId);
    if (!input) return;
    if (input.type === 'password') {
        input.type = 'text';
        btn.innerHTML = '<i class="bi bi-eye-slash"></i>';
    } else {
        input.type = 'password';
        btn.innerHTML = '<i class="bi bi-eye"></i>';
    }
}

function updateEmployeeCodePreview(companyId) {
    if (!companyId) return;
    const previewMap = @json($companyCodePreviews ?? []);
    if (previewMap && previewMap[companyId]) {
        const previewInput = document.getElementById('employee_code_preview');
        if (previewInput) {
            previewInput.value = previewMap[companyId];
        }
    } else {
        fetch(`{{ route('admin.employee.preview-code') }}?company_id=${companyId}`)
            .then(res => res.json())
            .then(data => {
                if (data && data.code) {
                    const previewInput = document.getElementById('employee_code_preview');
                    if (previewInput) previewInput.value = data.code;
                }
            })
            .catch(() => {});
    }
}
